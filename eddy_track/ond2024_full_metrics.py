"""Full-horizon OND 2024 capture-rate chart and summary metrics table.

Reads 13 x 4 model-specific full-horizon comparisons and the position/amplitude
statistics generated by eddy_track.ond2024_full_plots. No detection or tracking.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from eddy_track.plot_comparison_skill import MODELS, LABELS, COLORS

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output_root",type=Path)
    args=parser.parse_args()
    root=args.output_root
    base=root/"COMPARISON_FULL"
    out=base/"FIGURES"
    out.mkdir(parents=True,exist_ok=True)
    rows=[]
    for cycle in sorted(p.name for p in base.glob("20??????") if p.is_dir()):
        for model in MODELS:
            path=base/cycle/model/"summary.csv"
            if not path.is_file():raise FileNotFoundError(path)
            df=pd.read_csv(path)
            required={"model","polarity","observed_initial_tracks","model_initial_tracks","matched_initial_tracks"}
            if not required.issubset(df):raise ValueError(f"{path}: missing {required-set(df)}")
            if len(df)!=2 or set(df.model)!={model} or set(df.polarity)!={"Cyclonic","Anticyclonic"}:
                raise ValueError(f"{path}: expected exactly both polarities for {model}")
            if df.duplicated(["model","polarity"]).any():raise ValueError(f"{path}: duplicated polarity")
            if (df.matched_initial_tracks>df.observed_initial_tracks).any():raise ValueError(f"{path}: matched > observed")
            rows.append({"cycle":cycle,"model":model,
                         "observed":int(df.observed_initial_tracks.sum()),
                         "modeled":int(df.model_initial_tracks.sum()),
                         "matched":int(df.matched_initial_tracks.sum())})
    if len(rows)!=52 or len({r["cycle"] for r in rows})!=13:
        raise ValueError(f"Expected 13 cycles x 4 models = 52 summaries; found {len(rows)}")
    by_cycle=pd.DataFrame(rows)
    if (by_cycle.observed<=0).any():raise ValueError("Zero observed initial eddies in a cycle")
    by_cycle["obs_capture_percent"]=100*by_cycle.matched/by_cycle.observed
    by_cycle.to_csv(out/"ond2024_full_eddy_capture_by_cycle.csv",index=False)
    summary=by_cycle.groupby("model",as_index=False).agg(
        cycles=("cycle","nunique"),
        observed_cycle_total=("observed","sum"),
        model_cycle_total=("modeled","sum"),
        matched_cycle_total=("matched","sum"),
        mean_cycle_capture_percent=("obs_capture_percent","mean"),
        std_cycle_capture_percent=("obs_capture_percent","std"))
    summary["pooled_obs_capture_percent"]=100*summary.matched_cycle_total/summary.observed_cycle_total
    summary["pooled_model_precision_percent"]=100*summary.matched_cycle_total/summary.model_cycle_total.replace(0,np.nan)
    summary.to_csv(out/"ond2024_full_eddy_capture_summary.csv",index=False)
    fig,ax=plt.subplots(figsize=(12,7))
    vals=[float(summary.loc[summary.model==m,"pooled_obs_capture_percent"].iloc[0]) for m in MODELS]
    bars=ax.bar(range(4),vals,color=[COLORS[m] for m in MODELS],width=.65)
    for bar,v in zip(bars,vals):
        ax.text(bar.get_x()+bar.get_width()/2,v+1,f"{v:.1f}%",ha="center",fontsize=15)
    ax.set_xticks(range(4),[LABELS[m] for m in MODELS])
    ax.set_ylim(0,max(100,max(vals)+10))
    ax.set_ylabel("Observed eddies initially matched (%)")
    ax.set_title("OND 2024 — Full-horizon initial eddy capture rate")
    ax.grid(axis="y",alpha=.2)
    ax.set_axisbelow(True)
    fig.text(.5,.025,"50 km, same-polarity one-to-one matching at each model's initialization; 13 weekly cycles.\n"
             "Capture is an initialization metric, not a 28-day averaged detection rate.",
             ha="center",fontsize=10,color="#555555")
    fig.subplots_adjust(bottom=.20)
    fig.savefig(out/"ond2024_full_eddy_capture_rate.png",dpi=250,bbox_inches="tight")
    plt.close(fig)

    pos=pd.read_csv(out/"ond2024_full_position_error.csv")
    amp=pd.read_csv(out/"ond2024_full_amplitude_error.csv")
    metric_rows=[]
    for model in MODELS:
        p=pos[pos.model==model]
        a=amp[amp.model==model]
        c=summary[summary.model==model]
        if p.empty or a.empty or len(c)!=1:raise ValueError(f"Missing full-horizon statistics for {model}")
        if p.n.sum()<=0 or a.n.sum()<=0:raise ValueError(f"Missing matched samples for {model}")
        metric_rows.append({
            "model":LABELS[model],
            "position_error_weighted_daily_median_km":float(np.average(p["median"],weights=p.n)),
            "amplitude_error_weighted_daily_median_cm":float(np.average(a["median"],weights=a.n))*100,
            "initial_obs_capture_percent":float(c.pooled_obs_capture_percent.iloc[0]),
            "matched_position_samples":int(p.n.sum()),
            "matched_amplitude_samples":int(a.n.sum()),
            "initial_matched_eddies_cycle_total":int(c.matched_cycle_total.iloc[0]),
            "initial_observed_eddies_cycle_total":int(c.observed_cycle_total.iloc[0]),
        })
    metrics=pd.DataFrame(metric_rows)
    metrics.to_csv(out/"ond2024_full_metrics_table.csv",index=False)
    labels=["System","Position error\n(km)","Amplitude error\n(cm)","Initial capture\n(%)","Position\nsamples"]
    cells=[[r["model"],f'{r["position_error_weighted_daily_median_km"]:.2f}',
            f'{r["amplitude_error_weighted_daily_median_cm"]:.2f}',
            f'{r["initial_obs_capture_percent"]:.1f}',
            f'{r["matched_position_samples"]:,}'] for r in metric_rows]
    fig,ax=plt.subplots(figsize=(13,4.8))
    ax.axis("off")
    ax.set_title("OND 2024 — Full-horizon eddy forecast metrics",fontsize=20,pad=20)
    tab=ax.table(cellText=cells,colLabels=labels,cellLoc="center",colLoc="center",
                 loc="center",colWidths=[.28,.19,.20,.20,.13])
    tab.auto_set_font_size(False)
    tab.set_fontsize(12)
    tab.scale(1,2.5)
    for j in range(len(labels)):
        tab[(0,j)].set_facecolor("#e9edf2")
        tab[(0,j)].set_text_props(weight="bold")
    for i,model in enumerate(MODELS,start=1):
        tab[(i,0)].set_text_props(weight="bold",color=COLORS[model])
        if i%2==0:
            for j in range(len(labels)):tab[(i,j)].set_facecolor("#f7f8fa")
    fig.text(.5,.05,"Full model-specific horizons (10/9/10/28 days); 13 OND cycles; 50 km initial matching.\n"
             "Errors: sample-weighted averages of forecast-day medians, not pooled medians. Capture: matched / observed at initialization.",
             ha="center",fontsize=10,color="#555555")
    fig.savefig(out/"ond2024_full_metrics_table.png",dpi=240,bbox_inches="tight")
    plt.close(fig)
    print("Saved full-horizon capture rate and metrics table to",out)
    print(metrics.to_string(index=False))

if __name__=="__main__":main()
